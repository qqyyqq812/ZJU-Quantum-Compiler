#!/bin/bash
# Teacher-facing wrapper around the public smoke demo.

set -euo pipefail

PROJECT_DIR="$(cd "$(dirname "$0")" && pwd)"
PUBLIC_DIR="${PROJECT_DIR}/results/public_demo"
TEACHER_DIR="${PROJECT_DIR}/results/teacher_demo"

bash "${PROJECT_DIR}/run_public_demo.sh"

rm -rf "${TEACHER_DIR}"
mkdir -p "$(dirname "${TEACHER_DIR}")"
cp -a "${PUBLIC_DIR}" "${TEACHER_DIR}"

cat > "${TEACHER_DIR}/SCORING_INDEX.md" <<'EOF'
# Teacher acceptance scoring index

This directory is generated by `bash run_teacher_eval.sh`.

Current project position:

- NPQR is the default route.
- SABRE is the comparison baseline.
- The backend returns routed QASM, SWAP count, depth, elapsed time, and a route trace.
- The default model is `models/default/npqr-default.pt`.
- The project claim is a neural-assisted routing workflow, not a universal win over SABRE.

Generated files:

- `01_qcompiler_info.txt`: CLI and topology status.
- `02_default_model.txt`: checked-in model file status.
- `03_api_status.json`: REST status response.
- `04_npqr_compile.json`: NPQR compile smoke.
- `05_sabre_compile.json`: SABRE baseline smoke.
EOF

echo "Teacher demo copied to ${TEACHER_DIR}"
